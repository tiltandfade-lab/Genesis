#!/usr/bin/env python3
"""Genesis build — generate data/sprite-registry.js (docs/SPRITE-TRANSITION.md T3).

Joins a v2 sprite-sheet manifest (docs/SPRITE-TRANSITION.md "Shared data shapes" — normally
`dev/sprite-manifests/v2-manifest.json`, generated by T2's build/gen-sprite-sheet-manifests.py)
against `dev/model-qa/realm-bestiary-draft.json` (the live creature corpus) and
`dev/model-qa/sprite-tags-overlay.json` (the Adam redline/vision-scan overlay), and emits
`data/sprite-registry.js` — a plain top-level `SPRITE_REGISTRY` global, classic-script style
(one entry per line, GENERATED header, never hand-edited).

T2 hasn't landed a real manifest yet, so this run targets the committed FIXTURE at
`dev/fixtures/v2-manifest.json` (2 realms x 2 kinds, >=30 cells, mixed join/non-join —
docs/SPRITE-TRANSITION.md T3 "OUT OF SCOPE" note). Pass --manifest to point at a real one
once T2 lands; the orchestrator re-runs generation against the real manifest at integration.

Join: cell `name` <-> bestiary creature `name` within the same `realm`. Exact match first,
then a case/punctuation-insensitive fallback. Unjoined cells are NEVER dropped — they emit
with role/cr/type/size/frame == null and are added to a printed WARN list. Only `kind:"monster"`
cells count toward the join-coverage stat (npc/animal/kid/pc kinds are not creature-bestiary
rows and are expected to miss).

Per-slug emitted shape (fixed by the spec):
  { realm, kind, name, role, cr, type, size, frame, tags, sheet, cell, status }
`tags` defaults to [realm, kind, role, type-lower, size-lower] (falsy fields dropped), unless
the overlay supplies a `tags` array for that slug, which REPLACES the auto set entirely (the
overlay's `tags`/`reusable`/`redlined` keys are deep-merged onto the entry, last, always
winning). `status` is "cut" iff `assets/sprites/<slug>.png` exists on disk at generation time,
else "pending".

--check validates without writing:
  - manifest parses, every slug matches ^spr-
  - no slug collisions across sheets
  - join coverage for kind:"monster" cells only (informational; not a failing gate here —
    dev/verify-sprite-registry.mjs is the gate that enforces >=90%)

Run: python3 build/gen-sprite-registry.py                      (writes data/sprite-registry.js,
                                                                  fixture manifest by default)
     python3 build/gen-sprite-registry.py --manifest <path>    (point at a real v2 manifest)
     python3 build/gen-sprite-registry.py --check               (validate only, no write)

After regenerating: python3 build/check-manifest.py && node dev/verify-sprite-registry.mjs
"""
import argparse
import json
import os
import re
import sys
from collections import OrderedDict

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
# T2's real manifest landed 2026-07-09 — the fixture at dev/fixtures/v2-manifest.json
# remains for the verify harness only.
DEFAULT_MANIFEST = os.path.join(ROOT, "dev", "sprite-manifests", "v2-manifest.json")
BESTIARY_DRAFT = os.path.join(ROOT, "dev", "model-qa", "realm-bestiary-draft.json")
OVERLAY = os.path.join(ROOT, "dev", "model-qa", "sprite-tags-overlay.json")
SPRITES_DIR = os.path.join(ROOT, "assets", "sprites")
OUT = os.path.join(ROOT, "data", "sprite-registry.js")
REJECTS = os.path.join(ROOT, "dev", "sprite-manifests", "REJECTS.md")

SLUG_RE = re.compile(r"^spr-")


def load_json(path, default=None):
    if not os.path.exists(path):
        if default is not None:
            return default
        raise SystemExit(f"missing required file: {path}")
    with open(path, "r", encoding="utf-8") as f:
        return json.load(f)


def norm(s):
    """case/punctuation-insensitive fallback key for the name join."""
    return re.sub(r"[^a-z0-9]+", "", s.lower())


def load_bestiary_by_realm():
    draft = load_json(BESTIARY_DRAFT)
    by_realm = {}
    for entry in draft:
        if "realm" not in entry or "creatures" not in entry:
            continue  # skip the leading _review sidecar block
        realm = entry["realm"]
        exact = {}
        loose = {}
        for c in entry["creatures"]:
            exact[c["name"]] = c
            loose.setdefault(norm(c["name"]), c)
        by_realm[realm] = {"exact": exact, "loose": loose}
    # The "fantasy" sheet realm is the base game's own 510-entry bestiary (data/bestiary.js),
    # not a realm block in the draft JSON — join it against BESTIARY directly (integration fix
    # 2026-07-09; without this every fantasy monster cell reads as unjoined and coverage lies).
    bjs = open(os.path.join(ROOT, "data", "bestiary.js"), encoding="utf-8").read()
    exact, loose = {}, {}
    for m in re.finditer(r'"([a-z0-9-]+)":\s*\{[^{}]*?"name":\s*"((?:[^"\\]|\\.)*)"', bjs):
        key, name = m.group(1), json.loads('"' + m.group(2) + '"')
        c = {"name": name, "frame": key, "role": None, "cr": None, "type": None, "size": None}
        for fld in ("cr", "role", "type", "size"):
            fm = re.search(r'"%s":\s*("(?:[^"\\]|\\.)*"|[0-9.]+)' % fld, bjs[m.start():m.start() + 600])
            if fm:
                try:
                    c[fld] = json.loads(fm.group(1))
                except ValueError:
                    pass
        exact.setdefault(name, c)
        loose.setdefault(norm(name), c)
    by_realm["fantasy"] = {"exact": exact, "loose": loose}
    return by_realm


def join_creature(realm, name, bestiary_by_realm):
    realm_idx = bestiary_by_realm.get(realm)
    if not realm_idx:
        return None
    if name in realm_idx["exact"]:
        return realm_idx["exact"][name]
    return realm_idx["loose"].get(norm(name))


def auto_tags(realm, kind, role, ctype, size):
    tags = []
    for v in (realm, kind, role, (ctype or "").lower() or None, (size or "").lower() or None):
        if v:
            tags.append(v)
    return tags


def js_str(v):
    return json.dumps(v)


def emit_entry(slug, e):
    fields = []
    fields.append(f'realm:{js_str(e["realm"])}')
    fields.append(f'kind:{js_str(e["kind"])}')
    fields.append(f'name:{js_str(e["name"])}')
    fields.append(f'role:{js_str(e["role"]) if e["role"] is not None else "null"}')
    fields.append(f'cr:{json.dumps(e["cr"]) if e["cr"] is not None else "null"}')
    fields.append(f'type:{js_str(e["type"]) if e["type"] is not None else "null"}')
    fields.append(f'size:{js_str(e["size"]) if e["size"] is not None else "null"}')
    fields.append(f'frame:{js_str(e["frame"]) if e["frame"] is not None else "null"}')
    fields.append("tags:" + json.dumps(e["tags"]))
    fields.append(f'sheet:{js_str(e["sheet"])}')
    fields.append(f'cell:{json.dumps(e["cell"])}')
    fields.append(f'status:{js_str(e["status"])}')
    if e.get("reusable") is not None:
        fields.append(f'reusable:{js_str(e["reusable"])}')
    if e.get("redlined") is not None:
        fields.append("redlined:" + json.dumps(bool(e["redlined"])))
    if e.get("scale") is not None:
        fields.append(f'scale:{json.dumps(e["scale"])}')
    if e.get("verdict") is not None:
        fields.append(f'verdict:{js_str(e["verdict"])}')
    if e.get("note") is not None:
        fields.append(f'note:{js_str(e["note"])}')
    return " \"" + slug + "\": {" + ", ".join(fields) + "},\n"


HEADER = (
    "/* GENERATED by build/gen-sprite-registry.py from a v2 sprite-sheet manifest "
    "(dev/sprite-manifests/v2-manifest.json once T2 lands; dev/fixtures/v2-manifest.json "
    "until then) + dev/model-qa/realm-bestiary-draft.json + dev/model-qa/sprite-tags-overlay.json "
    "— never hand-edit. docs/SPRITE-TRANSITION.md T3: SPRITE_REGISTRY[slug] = "
    "{realm, kind, name, role, cr, type, size, frame, tags, sheet, cell, status}. "
    "status:\"cut\" iff assets/sprites/<slug>.png exists at generation time, else \"pending\". "
    "Join: cell name <-> realm-bestiary-draft.json creature name within the same realm "
    "(exact, then case/punct-insensitive); unjoined cells keep role/cr/type/size/frame:null "
    "and are never dropped. tags default to [realm,kind,role,type,size] lowercased; the "
    "overlay's tags (when present for a slug) replace the auto set. Regenerate; never hand-edit. */\n"
)


def build_registry(manifest_path, check_only=False, overlay_path=OVERLAY, out_path=OUT):
    manifest = load_json(manifest_path)
    bestiary_by_realm = load_bestiary_by_realm()
    overlay = load_json(overlay_path, default={})
    overlay = {k: v for k, v in overlay.items() if not k.startswith("_")}

    entries = OrderedDict()
    seen_slugs = {}
    warn_unjoined = []
    monster_total = 0
    monster_joined = 0
    bad_slugs = []
    sheet_meta = {}   # sheet id -> {sourceFile, sourceSection} (for the rejects report)
    cell_cue = {}     # slug -> the manifest cell's cue text (the regen prompt fragment)

    for sheet in manifest.get("sheets", []):
        sheet_id = sheet["id"]
        realm = sheet["realm"]
        kind = sheet["kind"]
        sheet_meta[sheet_id] = {
            "sourceFile": sheet.get("sourceFile"), "sourceSection": sheet.get("sourceSection"),
        }
        for cell in sheet.get("cells", []):
            slug = cell["slug"]
            name = cell["name"]
            n = cell["n"]

            if not SLUG_RE.match(slug):
                bad_slugs.append(slug)

            if slug in seen_slugs:
                raise SystemExit(
                    f"slug collision: '{slug}' used by both "
                    f"{seen_slugs[slug]} and {sheet_id}#{n}"
                )
            seen_slugs[slug] = f"{sheet_id}#{n}"

            match = join_creature(realm, name, bestiary_by_realm)
            if kind == "monster":
                monster_total += 1
                if match:
                    monster_joined += 1
            if not match:
                warn_unjoined.append(f"{sheet_id}#{n} '{name}' (realm={realm}, kind={kind})")

            role = match["role"] if match else None
            cr = match["cr"] if match else None
            ctype = match["type"] if match else None
            size = match["size"] if match else None
            frame = match["frame"] if match else None

            tags = auto_tags(realm, kind, role, ctype, size)
            ov = overlay.get(slug, {})
            if isinstance(ov.get("tags"), list):
                tags = ov["tags"]

            entry = {
                "realm": realm, "kind": kind, "name": name, "role": role, "cr": cr,
                "type": ctype, "size": size, "frame": frame, "tags": tags,
                "sheet": sheet_id, "cell": n,
                "status": "cut" if os.path.exists(os.path.join(SPRITES_DIR, f"{slug}.png")) else "pending",
            }
            # Overlay `name` = relabel-to-art (Adam's 2026-07-10 ruling: when the
            # generated art doesn't match the rostered subject, the display noun
            # follows the ART; the orphaned role goes to the regen queue). Applied
            # AFTER the bestiary join so mechanical stats still key off the
            # manifest's original name.
            if isinstance(ov.get("name"), str) and ov["name"].strip():
                entry["name"] = ov["name"].strip()
            if "reusable" in ov:
                entry["reusable"] = ov["reusable"]
            if "redlined" in ov:
                entry["redlined"] = ov["redlined"]
            # Sprite-review overlay keys (dev/sprite-review.py writes these): scale is the
            # per-slug render-height multiplier (heads-line-up calibration; theater billboard
            # consumes it), verdict is the pass/fail ruling ("fail" makes the theater fall
            # through to the 3D chain), note is the reviewer's free-text reason.
            if isinstance(ov.get("scale"), (int, float)) and ov["scale"] > 0 and ov["scale"] != 1:
                entry["scale"] = round(float(ov["scale"]), 3)
            if ov.get("verdict") in ("pass", "fail"):
                entry["verdict"] = ov["verdict"]
            if isinstance(ov.get("note"), str) and ov["note"].strip():
                entry["note"] = ov["note"].strip()
            if cell.get("cue"):
                cell_cue[slug] = cell["cue"]
            entries[slug] = entry

    coverage = (monster_joined / monster_total * 100) if monster_total else 100.0

    print(f"sheets: {len(manifest.get('sheets', []))}  cells: {len(entries)}")
    print(f"monster-kind join coverage: {monster_joined}/{monster_total} ({coverage:.1f}%)")
    if warn_unjoined:
        print(f"WARN — {len(warn_unjoined)} unjoined cell(s):")
        for w in warn_unjoined:
            print("  -", w)
    if bad_slugs:
        print(f"BAD SLUGS (do not match ^spr-): {bad_slugs}", file=sys.stderr)
        if not check_only:
            raise SystemExit(1)

    if check_only:
        return entries, coverage, warn_unjoined

    lines = [HEADER, "const SPRITE_REGISTRY={\n"]
    for slug, e in entries.items():
        lines.append(emit_entry(slug, e))
    lines.append("};\n")
    with open(out_path, "w", encoding="utf-8") as f:
        f.write("".join(lines))
    print(f"wrote {out_path} ({len(entries)} entries)")

    # Rejects report — the regen shopping list. Real runs only (the verify harness's
    # --out scratch runs must stay side-effect-free).
    if out_path == OUT:
        write_rejects(entries, sheet_meta, cell_cue)
    return entries, coverage, warn_unjoined


def write_rejects(entries, sheet_meta, cell_cue):
    """dev/sprite-manifests/REJECTS.md — every verdict:"fail" sprite grouped by sheet, with
    the manifest cue (the regen prompt fragment) + the reviewer's note. GENERATED — rulings
    live in dev/model-qa/sprite-tags-overlay.json (via dev/sprite-review.py); regenerate,
    never hand-edit."""
    fails = [(slug, e) for slug, e in entries.items() if e.get("verdict") == "fail"]
    by_sheet = OrderedDict()
    for slug, e in fails:
        by_sheet.setdefault(e["sheet"], []).append((slug, e))

    out = [
        "# Sprite rejects — regen list\n\n",
        "GENERATED by build/gen-sprite-registry.py from the sprite-review overlay "
        "(dev/model-qa/sprite-tags-overlay.json) — never hand-edit; re-rule in the review "
        "tool (python3 dev/sprite-review.py) and regenerate.\n\n",
        f"**{len(fails)} rejected** across {len(by_sheet)} sheet(s).\n\n",
    ]
    for sheet_id, items in by_sheet.items():
        meta = sheet_meta.get(sheet_id, {})
        src = meta.get("sourceFile") or "?"
        sec = meta.get("sourceSection")
        out.append(f"## {sheet_id} — {len(items)} reject(s)\n")
        out.append(f"prompt source: `{src}`{f' · {sec}' if sec else ''}\n\n")
        for slug, e in sorted(items, key=lambda kv: kv[1]["cell"]):
            note = f" — **note:** {e['note']}" if e.get("note") else ""
            cue = f"\n  - cue: {cell_cue[slug]}" if cell_cue.get(slug) else ""
            out.append(f"- cell {e['cell']} — **{e['name']}** (`{slug}`){note}{cue}\n")
        out.append("\n")
    if not fails:
        out.append("_No rejects — nothing awaiting regen._\n")
    with open(REJECTS, "w", encoding="utf-8") as f:
        f.write("".join(out))
    print(f"wrote {REJECTS} ({len(fails)} rejects)")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--manifest", default=DEFAULT_MANIFEST)
    ap.add_argument("--overlay", default=OVERLAY, help="override the overlay path (testing)")
    ap.add_argument("--out", default=OUT, help="override the output path (testing)")
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    build_registry(args.manifest, check_only=args.check, overlay_path=args.overlay, out_path=args.out)


if __name__ == "__main__":
    main()
