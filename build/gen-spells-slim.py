#!/usr/bin/env python3
"""Genesis build — generate data/spells-slim.js from Reference/SRD-Data/spells.json.

The creator's spell-selection step needs the cantrip (level 0) and level-1 spell
lists, filtered by class, available client-side. A file:// page can't fetch() JSON
but loads a <script src> fine (the single-file design constraint), so we emit a JS
global `SPELLS_SLIM` rather than ship the JSON for the creator to fetch.

Slim = name, level, school, classes[], and a short one-line flavor (first sentence
of the description, trimmed). Full spell text still lives in spells.json for the
DM's mid-scene lookups — this is only the picker surface.

This is a generated artifact — never hand-edit data/spells-slim.js; edit spells.json
(the source) and re-run this. Idempotent.
"""
import json, os, re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC  = os.path.join(ROOT, "Reference", "SRD-Data", "spells.json")
OUT  = os.path.join(ROOT, "data", "spells-slim.js")

def short_flavor(desc):
    if not desc:
        return ""
    # first sentence, collapse whitespace, cap length
    s = re.sub(r"\s+", " ", desc).strip()
    m = re.match(r"(.+?[.!?])(\s|$)", s)
    s = m.group(1) if m else s
    if len(s) > 120:
        s = s[:117].rstrip() + "…"
    return s

def full_text(desc):
    """The complete spell description, whitespace-collapsed — the player reads this
    while choosing (the picker's hover popover). No truncation."""
    if not desc:
        return ""
    return re.sub(r"\s+", " ", desc).strip()

def main():
    spells = json.load(open(SRC, encoding="utf-8"))
    slim = []
    for sp in spells:
        lvl = sp.get("level", 0)
        if lvl > 1:          # creator only needs cantrips (0) + level 1
            continue
        slim.append({
            "name":    sp["name"],
            "level":   lvl,
            "school":  sp.get("school", ""),
            "classes": sp.get("classes", []),
            "flavor":  short_flavor(sp.get("description", "")),
            "text":    full_text(sp.get("description", "")),
        })
    slim.sort(key=lambda s: (s["level"], s["name"]))
    body = ",\n".join("  " + json.dumps(s, ensure_ascii=False) for s in slim)
    header = (
        "/* GENESIS DATA (generated) — data/spells-slim.js\n"
        "   Cantrip + level-1 spell picker surface for the character creator.\n"
        "   GENERATED by build/gen-spells-slim.py from Reference/SRD-Data/spells.json — DO NOT hand-edit.\n"
        "   Classic <script> (shared global scope); defines window.SPELLS_SLIM. */\n"
    )
    js = header + "const SPELLS_SLIM=[\n" + body + "\n];\n"
    with open(OUT, "w", encoding="utf-8") as f:
        f.write(js)
    n0 = sum(1 for s in slim if s["level"] == 0)
    n1 = sum(1 for s in slim if s["level"] == 1)
    print(f"wrote {OUT}: {len(slim)} spells ({n0} cantrips, {n1} level-1)")

if __name__ == "__main__":
    main()
