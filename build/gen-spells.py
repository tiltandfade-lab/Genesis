#!/usr/bin/env python3
"""Genesis build — generate data/spells.js (the FULL 339-spell index) from
Reference/SRD-Data/spells.json.

docs/SRD-MECHANIZATION.md §2 (Decision 1: FULL index). Concentration enforcement needs the
`concentration` flag on every castable spell; ritual casting needs `ritual`; the DM's mid-scene
lookups want the whole record. So this emits EVERY spell at EVERY level (including spells beyond
the T1/T2 cast ceiling — high-level spells are valuable narrative content: scrolls, NPC casters,
foreshadowing). data/spells-slim.js (build/gen-spells-slim.py) stays the creator's cantrip+L1
FILTERED VIEW onto this full index.

Emits a <script> global `SPELLS` (array) + `SPELLS_BY_NAME` (name→record, normalized key), so a
file:// page loads it as <script src> (no fetch). Carries per spell:
  name, level, school, classes[], castingTime, range, components, duration,
  ritual (bool), concentration (bool), atHigherLevels (str),
  save {ability, ...} | null   — parsed from the description's "X saving throw"
  attack (bool)                 — parsed from "spell attack"
  flavor (one-line), text (full description, whitespace-collapsed)

This is a GENERATED artifact — never hand-edit data/spells.js; edit spells.json (the source) and
re-run this. Idempotent.
"""
import json, os, re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC  = os.path.join(ROOT, "Reference", "SRD-Data", "spells.json")
OUT  = os.path.join(ROOT, "data", "spells.js")

ABIL = {"Strength": "str", "Dexterity": "dex", "Constitution": "con",
        "Intelligence": "int", "Wisdom": "wis", "Charisma": "cha"}

def norm_name(name):
    """Mirror engine.combat itemKey / dmRollFor normalization: fold curly quote, collapse ws,
    trim, lowercase — the key the app looks a spell up by."""
    return re.sub(r"\s+", " ", str(name or "").replace("’", "'")).strip().lower()

def collapse(s):
    return re.sub(r"\s+", " ", (s or "")).strip()

def short_flavor(desc):
    if not desc:
        return ""
    s = collapse(desc)
    m = re.match(r"(.+?[.!?])(\s|$)", s)
    s = m.group(1) if m else s
    if len(s) > 120:
        s = s[:117].rstrip() + "…"
    return s

def parse_save(desc):
    """The FIRST '<Ability> saving throw' the spell forces (the DM resolves the foe's save against
    spellSaveDC — docs/SRD-MECHANIZATION.md §1/§2). Returns {'ability': 'dex'} or None."""
    m = re.search(r"(Strength|Dexterity|Constitution|Intelligence|Wisdom|Charisma)\s+saving throw", desc)
    return {"ability": ABIL[m.group(1)]} if m else None

def parse_attack(desc):
    return bool(re.search(r"spell attack", desc, re.I))

def clean_casting_time(ct):
    """A couple of SRD entries carry a hyphenation artifact ('immedi- ately'); collapse it."""
    return collapse((ct or "").replace("- ", ""))

def main():
    spells = json.load(open(SRC, encoding="utf-8"))
    out = []
    for sp in spells:
        desc = sp.get("description", "")
        rec = {
            "name":           sp["name"],
            "level":          sp.get("level", 0),
            "school":         sp.get("school", ""),
            "classes":        sp.get("classes", []),
            "castingTime":    clean_casting_time(sp.get("castingTime", "")),
            "range":          collapse(sp.get("range", "")),
            "components":     collapse(sp.get("components", "")),
            "duration":       collapse(sp.get("duration", "")),
            "ritual":         bool(sp.get("ritual", False)),
            "concentration":  bool(sp.get("concentration", False)),
            "atHigherLevels": collapse(sp.get("atHigherLevels", "")),
            "save":           parse_save(desc),
            "attack":         parse_attack(desc),
            "flavor":         short_flavor(desc),
            "text":           collapse(desc),
        }
        out.append(rec)
    out.sort(key=lambda s: (s["level"], s["name"]))

    body = ",\n".join("  " + json.dumps(s, ensure_ascii=False) for s in out)
    # SPELLS_BY_NAME: normalized-name → record, built in JS off SPELLS so there's one source (and the
    # normalization matches engine.combat itemKey). Keeps the file self-describing for the concentration
    # module's spellIndexByName lookup.
    header = (
        "/* GENESIS DATA (generated) — data/spells.js\n"
        "   The FULL 339-spell index (all levels): name/level/school/classes + castingTime/range/\n"
        "   components/duration + ritual/concentration + atHigherLevels + save/attack shape + flavor/text.\n"
        "   docs/SRD-MECHANIZATION.md §2 (Decision 1: FULL). Concentration/ritual enforcement + the DM's\n"
        "   mid-scene lookups read this; data/spells-slim.js stays the creator's cantrip+L1 filtered view.\n"
        "   GENERATED by build/gen-spells.py from Reference/SRD-Data/spells.json — DO NOT hand-edit.\n"
        "   Classic <script> (shared global scope); defines SPELLS + SPELLS_BY_NAME. */\n"
    )
    footer = (
        "\n];\n"
        "const SPELLS_BY_NAME=(function(){var m={};for(var i=0;i<SPELLS.length;i++){"
        "var k=String(SPELLS[i].name||'').replace(/\\u2019/g,\"'\").replace(/\\s+/g,' ').trim().toLowerCase();"
        "m[k]=SPELLS[i];}return m;})();\n"
    )
    js = header + "const SPELLS=[\n" + body + footer
    with open(OUT, "w", encoding="utf-8") as f:
        f.write(js)

    n_conc = sum(1 for s in out if s["concentration"])
    n_rit  = sum(1 for s in out if s["ritual"])
    n_save = sum(1 for s in out if s["save"])
    print(f"wrote {OUT}: {len(out)} spells ({n_conc} concentration, {n_rit} ritual, {n_save} with a save)")

if __name__ == "__main__":
    main()
