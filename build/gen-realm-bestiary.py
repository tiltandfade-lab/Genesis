#!/usr/bin/env python3
"""Genesis build — generate data/realm-bestiary.js from dev/model-qa/realm-bestiary-draft.json.

docs/REALM-ENRICHMENT-WRITING.md §2 (Unit W2). The realm creature layer was previously emitted
ad-hoc with no committed generator — a drift trap the edit-source->compile-artifact discipline
forbids. This script is the one command that regenerates it.

Source of truth: dev/model-qa/realm-bestiary-draft.json (post-fold, W1). Edit that file, then
re-run this. NEVER hand-edit data/realm-bestiary.js.

The draft JSON is a list of realm objects `{realm, creatures:[...]}`. An optional leading
`{"_review": [...]}` entry (no `realm`/`creatures` keys) carries flagged-for-Adam rows from the
W1 fold pass — it is skipped when emitting (informational only, never blocks a normal run).

Per-creature emitted shape (full field shape per spec, optional fields omitted when absent so the
file stays readable, one creature per line):
  {name, cr, role, type, size, frame, model, summary?, flavor?, desc?, traits?, source?, sourceNote?}

--check mode validates without writing:
  - every `frame` resolves in data/bestiary.js's BESTIARY keys
  - every `realm` is a member of data/realms.js's frozen REALM_IDS
  - no intra-realm exact-duplicate names
  - required fields present on every creature (name, cr, role, type, size, frame, model)
  Exit 0 = clean, exit 1 = problems found (printed to stderr).

Run: python3 build/gen-realm-bestiary.py            (writes data/realm-bestiary.js)
     python3 build/gen-realm-bestiary.py --check     (validates only, no write)

After regenerating: python3 build/check-manifest.py && node dev/verify-realm-wiring.mjs
"""
import json, os, re, sys
from collections import OrderedDict

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DRAFT = os.path.join(ROOT, "dev", "model-qa", "realm-bestiary-draft.json")
BESTIARY_JS = os.path.join(ROOT, "data", "bestiary.js")
REALMS_JS = os.path.join(ROOT, "data", "realms.js")
OUT = os.path.join(ROOT, "data", "realm-bestiary.js")

REQUIRED_FIELDS = ["name", "cr", "role", "type", "size", "frame", "model"]
# flavorTable/treasure/habitat/activity added by docs/MONSTER-FLAVOR-TABLES.md §2 (Phase 2b).
OPTIONAL_FIELDS = ["summary", "flavor", "desc", "traits", "flavorTable",
                   "treasure", "habitat", "activity", "source", "sourceNote"]

# MONSTER-FLAVOR-TABLES §1/§2 vocab + d8 shape rules (mirrors build/gen-monster-flavor.py so the
# two corpora validate identically). habitat = the frozen 17-value bestiary vocab; treasure = the
# §2 realm trio (a subset of bestiary's full treasure vocab — realm creatures only carry these).
HABITAT_VOCAB = {"any", "arctic", "cave", "coast", "deeplands", "desert", "elemental", "forest",
                 "grassland", "hill", "mountain", "planar", "ruins", "sea", "sky", "swamp", "urban"}
TREASURE_VOCAB = {"none", "individual", "hoard"}
FLAVOR_MODES = ("variant", "hook")
FLAVOR_LOW_BANDS = {1: "Grounded", 2: "Grounded", 3: "Grounded", 4: "Grounded", 5: "Grounded",
                    6: "Textured", 7: "Strange"}
FLAVOR_ROW8_BANDS = ("Volatile", "Mythic")

HEADER = (
    "/* GENERATED by build/gen-realm-bestiary.py from dev/model-qa/realm-bestiary-draft.json "
    "— never hand-edit. Realm creature layer (reskin: frame=stat chassis id in BESTIARY, "
    "model=render key/net-new description, desc/traits/source per docs/REALM-ENRICHMENT-WRITING.md; "
    "flavorTable/treasure/habitat/activity per docs/MONSTER-FLAVOR-TABLES.md §2). */\n"
)


def load_draft():
    with open(DRAFT, encoding="utf-8") as f:
        data = json.load(f, object_pairs_hook=OrderedDict)
    realms = [r for r in data if "realm" in r and "creatures" in r]
    review = next((r["_review"] for r in data if "_review" in r), [])
    return realms, review


def _extract_via_node(js_path, expose_expr, tmp_name):
    """Evaluate a real JS source file in a node vm context and pull out one top-level `const`'s
    value — the safest way to read the runtime shape without a hand-rolled JS parser drifting
    from it. Source is passed via a temp file (not argv) since data/bestiary.js is multi-MB and
    exceeds the OS argv-length limit."""
    import subprocess, tempfile
    src = open(js_path, encoding="utf-8").read()
    with tempfile.NamedTemporaryFile("w", suffix=".js", delete=False, dir=ROOT) as tf:
        tf.write(src)
        tf.write(f"\nrequire('fs').writeFileSync({json.dumps(tmp_name)}, JSON.stringify({expose_expr}));\n")
        script_path = tf.name
    out_path = os.path.join(ROOT, tmp_name)
    try:
        result = subprocess.run(["node", script_path], capture_output=True, text=True, cwd=ROOT)
        if result.returncode != 0:
            sys.stderr.write(f"gen-realm-bestiary: failed to extract via node ({js_path})\n")
            sys.stderr.write(result.stderr)
            sys.exit(1)
        with open(out_path, encoding="utf-8") as f:
            return json.load(f)
    finally:
        if os.path.exists(script_path):
            os.remove(script_path)
        if os.path.exists(out_path):
            os.remove(out_path)


def extract_bestiary_frame_ids():
    return set(_extract_via_node(BESTIARY_JS, "Object.keys(BESTIARY)", ".__realm_bestiary_frames_tmp.json"))


def extract_realm_ids():
    return set(_extract_via_node(REALMS_JS, "REALM_IDS", ".__realm_bestiary_realmids_tmp.json"))


def validate(realms, valid_frames, valid_realm_ids):
    problems = []
    for r in realms:
        realm = r["realm"]
        if realm not in valid_realm_ids:
            problems.append(f"realm '{realm}': not a member of REALM_IDS (data/realms.js)")
        seen = {}
        for c in r["creatures"]:
            missing = [f for f in REQUIRED_FIELDS if f not in c or c[f] in (None, "")]
            if missing:
                problems.append(f"{realm}/{c.get('name','<unnamed>')}: missing required field(s) {missing}")
            frame = c.get("frame")
            if frame is not None and frame not in valid_frames:
                problems.append(f"{realm}/{c.get('name','<unnamed>')}: invalid frame '{frame}'")
            nm = c.get("name", "").strip()
            if nm in seen:
                problems.append(f"{realm}/{nm}: intra-realm duplicate name")
            seen[nm] = True
            problems.extend(validate_flavor_fields(realm, c))
    return problems


def validate_flavor_fields(realm, c):
    """MONSTER-FLAVOR-TABLES §2 — validate the four Phase-2b story fields when present.
    All four are optional at the row level (a partially-authored draft still validates), but any
    that IS present must be well-formed: treasure/habitat vocab, and the d8 flavorTable shape
    (die/mode/8 rows/band ladder), mirroring build/gen-monster-flavor.py exactly."""
    problems = []
    where = f"{realm}/{c.get('name', '<unnamed>')}"

    if "treasure" in c and c["treasure"] not in (None, ""):
        if c["treasure"] not in TREASURE_VOCAB:
            problems.append(f"{where}: treasure {c['treasure']!r} not in {sorted(TREASURE_VOCAB)}")

    if "habitat" in c and c["habitat"] not in (None, ""):
        hab = c["habitat"]
        if not isinstance(hab, list) or not hab:
            problems.append(f"{where}: habitat must be a non-empty array")
        else:
            bad = [h for h in hab if h not in HABITAT_VOCAB]
            if bad:
                problems.append(f"{where}: habitat value(s) {bad} not in the 17-value vocab")

    if "activity" in c and c["activity"] not in (None, ""):
        act = c["activity"]
        if not isinstance(act, list) or not (1 <= len(act) <= 2) or \
                any(not isinstance(a, str) or not a.strip() for a in act):
            problems.append(f"{where}: activity must be a list of 1-2 non-empty strings")

    if "flavorTable" in c and c["flavorTable"] not in (None, ""):
        ft = c["flavorTable"]
        if not isinstance(ft, dict):
            problems.append(f"{where}: flavorTable must be an object")
            return problems
        if ft.get("die") != "d8":
            problems.append(f"{where}: flavorTable.die must be \"d8\" (got {ft.get('die')!r})")
        if ft.get("mode") not in FLAVOR_MODES:
            problems.append(f"{where}: flavorTable.mode must be one of {FLAVOR_MODES} (got {ft.get('mode')!r})")
        rows = ft.get("rows")
        if not isinstance(rows, list) or len(rows) != 8:
            problems.append(f"{where}: flavorTable.rows must have exactly 8 rows "
                            f"(got {len(rows) if isinstance(rows, list) else type(rows).__name__})")
            return problems
        apex_role = str(c.get("role") or "").lower() == "apex"
        seen_n = set()
        for row in rows:
            if not isinstance(row, dict):
                problems.append(f"{where}: flavorTable row {row!r} must be an object")
                continue
            n, band, text = row.get("n"), row.get("band"), row.get("text")
            if n not in range(1, 9):
                problems.append(f"{where}: flavorTable row n must be 1..8 (got {n!r})")
                continue
            seen_n.add(n)
            if not text or not isinstance(text, str) or not text.strip():
                problems.append(f"{where}: flavorTable row {n} missing text")
            if n <= 7:
                if band != FLAVOR_LOW_BANDS[n]:
                    problems.append(f"{where}: flavorTable row {n} band must be {FLAVOR_LOW_BANDS[n]!r} (got {band!r})")
            else:  # n == 8
                if band not in FLAVOR_ROW8_BANDS:
                    problems.append(f"{where}: flavorTable row 8 band must be one of {FLAVOR_ROW8_BANDS} (got {band!r})")
                if band == "Mythic" and not apex_role:
                    problems.append(f"{where}: flavorTable row 8 band is Mythic but role is not apex")
        if seen_n != set(range(1, 9)):
            problems.append(f"{where}: flavorTable rows must cover n=1..8 exactly once (got {sorted(seen_n)})")

    return problems


def js_literal(v):
    return json.dumps(v, ensure_ascii=False)


def emit_creature(c):
    parts = []
    for f in REQUIRED_FIELDS:
        parts.append(f"{js_literal(f)}:{js_literal(c[f])}")
    for f in OPTIONAL_FIELDS:
        if f in c and c[f] not in (None, ""):
            parts.append(f"{js_literal(f)}:{js_literal(c[f])}")
    return "{" + ",".join(parts) + "}"


def emit(realms):
    lines = [HEADER, "const REALM_BESTIARY={\n"]
    for i, r in enumerate(realms):
        realm = r["realm"]
        creature_strs = ",".join(emit_creature(c) for c in r["creatures"])
        comma = "," if i < len(realms) - 1 else ""
        lines.append(f" {js_literal(realm)}:[{creature_strs}]{comma}\n")
    lines.append("};\n")
    return "".join(lines)


def main():
    check_only = "--check" in sys.argv[1:]
    realms, review = load_draft()
    valid_frames = extract_bestiary_frame_ids()
    valid_realm_ids = extract_realm_ids()
    problems = validate(realms, valid_frames, valid_realm_ids)

    if problems:
        sys.stderr.write(f"gen-realm-bestiary --check: {len(problems)} problem(s) found:\n")
        for p in problems:
            sys.stderr.write(f"  - {p}\n")
        sys.exit(1)

    if check_only:
        total = sum(len(r["creatures"]) for r in realms)
        print(f"gen-realm-bestiary --check: clean. {total} creatures across {len(realms)} realms. "
              f"({len(review)} _review flag(s) pending in the draft, informational only.)")
        sys.exit(0)

    out = emit(realms)
    with open(OUT, "w", encoding="utf-8") as f:
        f.write(out)
    total = sum(len(r["creatures"]) for r in realms)
    print(f"gen-realm-bestiary: wrote {OUT} — {total} creatures across {len(realms)} realms.")


if __name__ == "__main__":
    main()
