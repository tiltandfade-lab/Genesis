/* dev/model-qa/floor-fixtures.mjs — writes dev/model-qa/battlemap-fixtures.js with FLOOR-GATE cases:
   one board per (env, rolled-floor-signal) so the visual gate can confirm theaterFloorMaterial +
   the procedural floor texture read as the material. Reuses battlemap-render.html + battlemap-capture.mjs.
   RUN (after the floor-textures branch is checked out): node dev/model-qa/floor-fixtures.mjs */
import { writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
const OUT = join(dirname(fileURLToPath(import.meta.url)), "battlemap-fixtures.js");

// each fixture: a rolled-ish segment carrying the fields theaterFloorMaterial reads (footing/biome/
// areaType/scene/dressing/description), a light, and a PC + one modeled foe.
const units = (foe, foeType) => ([
  { id: "pc", kind: "pc", creatureType: "humanoid", className: "fighter", band: "melee", lane: "C" },
  { id: "f1", kind: "foe", creatureType: foeType, size: "medium", statId: foe, band: "near", lane: "L", name: foe },
  { id: "f2", kind: "foe", creatureType: foeType, size: "medium", statId: foe, band: "near", lane: "R", name: foe },
]);
const scene = { cover: {}, zoneCover: {}, hazardZones: [], elevZones: [], hazards: [], exits: [] };
const F = [
  ["dungeon-flagstone", "dungeon", "torchlit", { id:"fd1", dims:"40' x 60'", areaType:"20'x30' Hall", scene:"worn flagstone floor, cut paving underfoot", sensory:"cold stone" }, "skeleton", "humanoid"],
  ["dungeon-cave", "dungeon", "torchlit", { id:"fd2", dims:"40' x 60'", areaType:"Cavern", scene:"a rough natural cavern, raw bedrock and loose rock", sensory:"damp rock" }, "ghoul", "humanoid"],
  ["urban-cobble", "urban", "lamplit", { id:"fu1", dims:"40' x 60'", description:"a cobbled lane, rounded cobblestones slick with rain", dressing:{ text:"wet cobbles and a broken gutter" } }, "guard", "humanoid"],
  ["wild-grass", "wilderness", "daylit", { id:"fw1", dims:"40' x 60'", biome:"Grassland", biomeDesc:"open rolling grassland", footing:{ text:"Springy Turf / Tundra Moss" } }, "wolf", "beast"],
  ["wild-sand", "wilderness", "daylit", { id:"fw2", dims:"40' x 60'", biome:"Desert", biomeDesc:"wind-scoured dunes", footing:{ text:"Sun-Baked Hardpan / Salt Flat" } }, "giant-lizard", "beast"],
  ["wild-snow", "wilderness", "daylit", { id:"fw3", dims:"40' x 60'", biome:"Arctic", biomeDesc:"frozen tundra", footing:{ text:"Stomped Snow / Polished Ice" } }, "yeti", "humanoid"],
  ["wild-mud", "wilderness", "moonlit", { id:"fw4", dims:"40' x 60'", biome:"Swamp", biomeDesc:"reeking bog", footing:{ text:"Damp Loam / Firm Wet Sand" } }, "gray-ooze", "amorphous"],
  ["wild-forest", "wilderness", "daylit", { id:"fw5", dims:"40' x 60'", biome:"Forest", biomeDesc:"deep pinewood", footing:{ text:"Dry Leaf Litter / Shed Pine Needles" } }, "dire-wolf", "beast"],
];
const fixtures = F.map(([tag, env, light, segment, foe, foeType]) => ({
  name: `${tag} · floor`, tag, mode: "F", env, light, grid: "3x3", dims: segment.dims,
  summary: `floor signal: ${segment.footing?.text || segment.scene || segment.description || segment.biome}`,
  segment, scene, units: units(foe, foeType),
}));
writeFileSync(OUT, "/* GENERATED by floor-fixtures.mjs — floor-texture visual gate. */\nwindow.__BM_FIXTURES = " + JSON.stringify(fixtures, null, 2) + ";\n");
console.log(`wrote ${fixtures.length} floor fixtures -> battlemap-fixtures.js`);
