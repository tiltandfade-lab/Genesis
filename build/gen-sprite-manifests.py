#!/usr/bin/env python3
"""Genesis build — generate ChatGPT-ready sprite-sheet prompt manifests from data/bestiary.js.

docs/BATTLE-THEATER.md §3 needs low-poly-era 2D creature art (a T2-sprites fallback/pack
alternative) sourced the same way Adam's earlier art passes work: he pastes a fixed-format
prompt into ChatGPT, gets back a 6x6 grid sprite sheet (36 creatures/image) on a flat magenta
#FF00FF key background, and build/slice-sprites.py (sibling script) turns each sheet into
game-ready transparent PNGs at assets/sprites/<slug>.png.

This script does the planning half: read the 510-entry bestiary, cluster creatures into
style-coherent sheets (same creatureType together — undead with undead, beasts with beasts,
etc.), order each sheet's 36 cells big-to-small (large/imposing creatures on the top rows,
matching how FFT/Vagrant Story concept sheets read), and emit:

  dev/sprite-manifests/MASTER-SPEC.md — the master sprite specification: the locked style
                                          preamble + explicit projection/proportion/lighting/
                                          palette rules as ONE fenced paste-ready block, plus
                                          the reference-anchor step (generate + refine ONE
                                          definitive single sprite BEFORE running any sheet).
  dev/sprite-manifests/sheet-NN.md    — one ready-to-paste ChatGPT prompt per sheet: a
                                          one-line header, then the prompt in a fenced code
                                          block so it copies clean (.md not .txt — Adam's
                                          viewer can't open .txt).
  dev/sprite-manifests/heroes.md      — the SINGLES list: every creature with CR >= 3 plus
                                          anything role: leader gets its own paste-ready
                                          single-sprite prompt (sheets cover the bulk tiers;
                                          heroes get production singles, sliced one-at-a-time
                                          via slice-sprites.py --single <slug>).
  dev/sprite-manifests/manifest.json  — sheet -> ordered creature slug list + the "heroes"
                                          slug list (the contract slice-sprites.py reads).

GENERATED — never hand-edit dev/sprite-manifests/*; edit this script (or the bestiary
source it reads) and re-run. Idempotent (same bestiary in -> same sheets out).

Source of truth: data/bestiary.js (BESTIARY, generated by build/gen-bestiary.py from
Asset Library/Monsters & Enemies/*.md). We don't re-parse the markdown; we read the same
compiled JS object gen-bestiary.py already produced, via `node -e` (simplest tolerant way
to pull a `const BESTIARY = {...}` classic-script literal into structured data without
a hand-rolled JS parser).

Grouping / ordering rules (mechanical, no hand-curation):
  - Cluster key = BESTIARY[id].tags.type (creatureType: undead, beast, humanoid, dragon,
    fiend, aberration, celestial, construct, elemental, fey, giant, monstrosity, ooze,
    plant, swarm). A handful of entries have no parseable tags.type (bestiary parse gaps,
    e.g. custom homebrew stat blocks) -> bucketed into a same-name fallback cluster
    ("humanoid") inferred from the entry name, never invented lore.
  - Two known non-creature bestiary rows ("The Cultist Roster", "Gold Dragon Roster" -- doc
    headers, not stat blocks) are dropped; not a design call, just "not a creature."
  - Sheets are built by walking clusters in size order (most populous first) and packing
    each cluster's creatures into consecutive sheet slots, so a sheet is either one full
    cluster or a clean boundary between two adjacent clusters -- never a random shuffle.
  - Within a sheet, creatures sort by size descending (Gargantuan > Huge > Large > Medium >
    Small > Tiny), CR descending as the tiebreak -- "large creatures on the top rows" per
    the brief, since row-major fill means earlier-sorted = higher on the sheet.

Each sheet-NN.md's fenced block is ONE paste-ready prompt: the fixed style preamble
(verbatim, locked -- do not reword, Adam's ChatGPT keying workflow depends on the exact
phrasing) + a row-major numbered list of 36 (or fewer, on the last sheet) creatures, each
with a short mechanically-derived visual descriptor (name + creatureType + size + CR-band
adjective -- no invented lore, just what the stat block already says).

Heroes selection is mechanical too: CR >= 3 OR role == "leader" (role is bestiary
frontmatter gen-bestiary.py already carries; the leader flag catches the low-CR captains --
Berserker, Cultist Fanatic, Noble, Priest -- that read as named-NPC material despite CR).
"""
import json
import math
import os
import re
import subprocess
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
BESTIARY_JS = os.path.join(ROOT, "data", "bestiary.js")
OUT_DIR = os.path.join(ROOT, "dev", "sprite-manifests")

GRID = 6
CELLS_PER_SHEET = GRID * GRID  # 36

STYLE_PREAMBLE = (
    "A 6x6 grid sprite sheet, 36 distinct creatures, gritty PS1-era dark-fantasy pixel-art "
    "— Vagrant Story / Final Fantasy Tactics mood: desaturated earth tones, muddy "
    "oxblood/steel/bone palette, hard shadows, angular near-realistic proportions, never "
    "chibi, never cartoon. Each cell: ONE full-body creature, 3/4 view facing left, "
    "consistent scale and lighting across all cells. Entire background flat magenta "
    "#FF00FF, thin magenta gutters between cells, no labels, no text, no borders."
)

# The explicit rule block MASTER-SPEC.md carries alongside the preamble — the same style
# contract spelled out unambiguously, so a drifting ChatGPT generation can be corrected by
# re-pasting the specific violated rule rather than the whole vibe.
MASTER_SPEC_RULES = """Rules (each one binding):
- Projection/camera: every creature in 3/4 view, facing LEFT. No front-on, no profile, no back views.
- Proportions: angular, near-realistic. Never chibi, never cartoon, never cute.
- Lighting: single light source from the UPPER-LEFT, hard-edged shadows on the form. Same direction in every cell/image.
- Palette: desaturated earth tones only — oxblood, steel, bone, moss. No saturated brights, no neon.
- No outlines around figures. No drop shadows on the background. The figure ends where its pixels end.
- Background: entirely flat magenta #FF00FF, edge to edge. Nothing else touches the background — no gradients, no vignette, no texture.
- Scale: creature size consistent relative to its cell across the whole set (a wolf reads smaller than an ogre; two humanoids read the same height)."""

# Reference anchor: the calibration step run ONCE before any sheet — a single mid-CR
# humanoid, refined until the style is locked, then kept in-conversation as the anchor
# every subsequent generation is compared against.
REFERENCE_ANCHOR_PROMPT = (
    "ONE single sprite, centered, larger detail: a bandit — a seasoned humanoid creature, "
    "leather and steel, full body. Gritty PS1-era dark-fantasy pixel-art — Vagrant Story / "
    "Final Fantasy Tactics mood. 3/4 view facing left, angular near-realistic proportions, "
    "never chibi, never cartoon. Single light source from the upper-left, hard shadows. "
    "Desaturated palette: oxblood, steel, bone, moss. No outlines, no drop shadows. Entire "
    "background flat magenta #FF00FF."
)

# Per-hero single-sprite prompt template ({desc_line} = "Name — descriptor" from the same
# mechanical descriptor the sheets use).
SINGLE_PROMPT_TEMPLATE = (
    "ONE single sprite, centered, larger detail: {desc_line}, full body. Gritty PS1-era "
    "dark-fantasy pixel-art — Vagrant Story / Final Fantasy Tactics mood. 3/4 view facing "
    "left, angular near-realistic proportions, never chibi, never cartoon. Single light "
    "source from the upper-left, hard shadows. Desaturated palette: oxblood, steel, bone, "
    "moss. No outlines, no drop shadows. Entire background flat magenta #FF00FF."
)

HERO_CR_FLOOR = 3  # CR >= this ⇒ hero single (plus any role: leader regardless of CR)

# Non-creature bestiary rows (doc headers parsed as if they were stat blocks). Dropped —
# mechanical filter, not a curation call.
DROP_IDS = {
    "cultist-roster-base-2024-stat-blocks",
    "gold-dragon-roster-5e-2024-mechanics",
}

SIZE_ORDER = ["Gargantuan", "Huge", "Large", "Medium", "Small", "Tiny"]
SIZE_RANK = {s: i for i, s in enumerate(SIZE_ORDER)}

# Cluster display order: biggest/most-central clusters first, then the rest by population
# (computed at runtime) — this list only pins a few clusters that read best adjacent to each
# other stylistically (undead/fiend/aberration = "dark" register; beast/monstrosity/dragon =
# "wild" register; humanoid/giant = "civilized-ish" register; construct/elemental/ooze/plant/
# fey/celestial/swarm = the smaller "other" clusters). Any cluster not listed here sorts by
# population after the pinned ones.
CLUSTER_PRIORITY = [
    "undead", "fiend", "aberration",
    "dragon", "monstrosity", "beast",
    "giant", "humanoid",
    "construct", "elemental", "fey", "celestial", "ooze", "plant", "swarm",
]


def load_bestiary():
    """Pull BESTIARY out of the classic-script data/bestiary.js via node, tolerant of the
    fact it's a `const BESTIARY = {...}; const BESTIARY_BY_CR = ...` module, not JSON."""
    script = r"""
const fs = require('fs');
let src = fs.readFileSync(process.argv[1], 'utf8');
src = src.replace('const BESTIARY=', 'global.BESTIARY=');
src = src.replace(/const BESTIARY_BY_CR[\s\S]*$/, '');
eval(src);
process.stdout.write(JSON.stringify(Object.values(BESTIARY)));
"""
    try:
        out = subprocess.run(
            ["node", "-e", script, BESTIARY_JS],
            cwd=ROOT, capture_output=True, text=True, check=True,
        )
    except FileNotFoundError:
        print("ERROR: node is required to read data/bestiary.js (classic-script, not JSON).", file=sys.stderr)
        sys.exit(1)
    except subprocess.CalledProcessError as e:
        print("ERROR: node failed to load data/bestiary.js:\n" + e.stderr, file=sys.stderr)
        sys.exit(1)
    return json.loads(out.stdout)


def infer_fallback_type(name):
    """For the handful of entries with no parseable tags.type (bestiary parse gaps), infer
    a coarse creatureType from the name text alone — mechanical keyword match, same spirit
    as gen-bestiary.py's own derive_habitat heuristic. Never invents lore; falls back to
    'humanoid' (the single most common type) when nothing matches."""
    n = name.lower()
    checks = [
        ("undead", re.compile(r"\b(husk|wraith|zombie|skeleton|ghoul|ghost|shadow|lich|vampire|wight|revenant)\b")),
        ("dragon", re.compile(r"\bdragon\b")),
        ("beast", re.compile(r"\b(rat|wolf|bear|boar|spider|hound|serpent)\b")),
        ("fiend", re.compile(r"\b(demon|devil|fiend)\b")),
        ("humanoid", re.compile(r"\b(bandit|cultist|vagrant|druid|courier|enforcer)\b")),
        ("dragon", re.compile(r"\bwyvern\b")),
    ]
    for type_, rx in checks:
        if rx.search(n):
            return type_
    return "humanoid"


def infer_fallback_size(size_field):
    """A couple of entries carry a corrupted `size` (bestiary parse artifact, e.g. a
    truncated parenthetical instead of a size word). Fall back to Medium — the modal size —
    rather than guess further; this is a parse-quality gap in the source data, out of this
    script's scope to fix."""
    if size_field in SIZE_RANK:
        return size_field
    return "Medium"


def cr_band(cr):
    """CR banding for the visual-descriptor adjective. Coarse, mechanical, matches the
    tiers loot/threat already use elsewhere in the engine (T1..T4-ish bands)."""
    if cr is None:
        return "unremarkable"
    if cr < 1:
        return "unremarkable"
    if cr < 5:
        return "seasoned"
    if cr < 11:
        return "formidable"
    if cr < 17:
        return "armored and imposing"
    return "towering and legendary"


SIZE_ADJ = {
    "Tiny": "tiny",
    "Small": "small",
    "Medium": None,   # no adjective needed — Medium is the unmarked default
    "Large": "large",
    "Huge": "huge",
    "Gargantuan": "gargantuan",
}


def descriptor(entry, type_, size):
    """5-12 word mechanically-derived visual descriptor: name + creatureType + size + CR-band
    wording. No invented lore — just what the stat block already says, phrased as a sprite
    brief. e.g. 'Goblin — small, unremarkable humanoid, quick and vicious in dim light.'"""
    band = cr_band(entry.get("cr"))
    size_adj = SIZE_ADJ.get(size)
    bits = []
    if size_adj:
        bits.append(size_adj)
    bits.append(band)
    bits.append(type_)
    body = ", ".join(bits)
    return f"{body} creature"


def cluster_creatures(bestiary):
    clusters = {}
    for e in bestiary:
        if e["id"] in DROP_IDS:
            continue
        type_ = (e.get("tags") or {}).get("type")
        if not type_:
            type_ = infer_fallback_type(e["name"])
        size = (e.get("tags") or {}).get("size")
        size = size.capitalize() if isinstance(size, str) else None
        if size not in SIZE_RANK:
            size = infer_fallback_size(e.get("size"))
        clusters.setdefault(type_, []).append({
            "id": e["id"],
            "name": e["name"],
            "type": type_,
            "size": size,
            "cr": e.get("cr"),
            "role": e.get("role"),
        })
    for type_, items in clusters.items():
        items.sort(key=lambda c: (SIZE_RANK.get(c["size"], 3), -(c["cr"] or 0), c["name"]))
    return clusters


def ordered_cluster_names(clusters):
    pinned = [t for t in CLUSTER_PRIORITY if t in clusters]
    rest = sorted(
        (t for t in clusters if t not in CLUSTER_PRIORITY),
        key=lambda t: -len(clusters[t]),
    )
    return pinned + rest


def pack_sheets(clusters):
    """Walk clusters in priority order, packing creatures into sheets of 36. A sheet boundary
    only falls mid-cluster when a cluster doesn't divide evenly into 36 — the remainder just
    carries into the next sheet's first rows, keeping each sheet style-coherent at the seams
    (never an arbitrary shuffle across unrelated types)."""
    sheets = [[]]
    for type_ in ordered_cluster_names(clusters):
        for creature in clusters[type_]:
            if len(sheets[-1]) >= CELLS_PER_SHEET:
                sheets.append([])
            sheets[-1].append(creature)
    return sheets


def format_sheet_prompt(sheet_idx, creatures):
    lines = [STYLE_PREAMBLE, ""]
    n = len(creatures)
    for row in range(GRID):
        row_start = row * GRID
        if row_start >= n:
            break
        row_end = min(row_start + GRID, n)
        lines.append(f"Row {row + 1}:")
        for i in range(row_start, row_end):
            c = creatures[i]
            desc = descriptor(c, c["type"], c["size"])
            lines.append(f"{i + 1}. {c['name']} — {desc}")
    if n < CELLS_PER_SHEET:
        lines.append("")
        lines.append(
            f"(Partial sheet: {n} of {CELLS_PER_SHEET} cells specified above — leave the "
            f"remaining {CELLS_PER_SHEET - n} cells on the flat magenta background empty, "
            "or reuse the style for incidental creatures of the same type; slice-sprites.py "
            f"will be run with --expect {n}.)"
        )
    return "\n".join(lines) + "\n"


def format_sheet_md(sheet_idx, creatures):
    """The .md wrapper: one-line header (# Sheet NN — family (N creatures)), then the
    paste-ready prompt in a fenced code block so it copies clean out of any viewer."""
    family = " + ".join(sorted(set(c["type"] for c in creatures)))
    header = f"# Sheet {sheet_idx:02d} — {family} ({len(creatures)} creatures)"
    prompt = format_sheet_prompt(sheet_idx, creatures)
    return f"{header}\n\n```\n{prompt}```\n"


def format_master_spec_md():
    spec_block = STYLE_PREAMBLE + "\n\n" + MASTER_SPEC_RULES
    return f"""# Master sprite specification

GENERATED by build/gen-sprite-manifests.py — do not hand-edit; edit the generator and re-run.

The single style contract every sheet and every hero single is generated under. Paste the
block below at the top of the ChatGPT conversation ONCE, before anything else, so every
generation in that conversation inherits it.

```
{spec_block}
```

## Step 0 — the reference anchor (do this BEFORE any sheet)

Generate ONE definitive single sprite first and refine it until it is exactly right — this
becomes the style anchor the whole set is judged against. Use a mid-CR humanoid (a bandit):

```
{REFERENCE_ANCHOR_PROMPT}
```

Iterate on that one sprite (palette too saturated? proportions drifting cartoon? lighting
direction wrong?) by quoting the violated rule from the spec block above. Only when the
anchor is right, start `sheet-01.md` — in the SAME conversation, so the anchor stays in
context. If a later sheet drifts, point ChatGPT back at the anchor sprite.
"""


def format_heroes_md(heroes):
    lines = [
        f"# Heroes — production singles ({len(heroes)} creatures)",
        "",
        "GENERATED by build/gen-sprite-manifests.py — do not hand-edit; edit the generator and re-run.",
        "",
        f"Every bestiary entry with CR >= {HERO_CR_FLOOR}, plus every `role: leader` regardless of CR.",
        "Sheets cover the bulk tiers; these get individual full-detail sprites. Paste one block per",
        "generation (same conversation as the anchor + sheets, so the style holds). Slice each result:",
        "",
        "    python3 build/slice-sprites.py <hero.png> --single <slug>",
        "",
    ]
    for h in heroes:
        desc = descriptor(h, h["type"], h["size"])
        desc_line = f"{h['name']} — a {desc}"
        prompt = SINGLE_PROMPT_TEMPLATE.format(desc_line=desc_line)
        cr = h.get("cr")
        cr_txt = f"CR {cr:g}" if cr is not None else "CR ?"
        role_txt = " · leader" if h.get("role") == "leader" else ""
        lines.append(f"## {h['name']} (`{h['id']}`) — {cr_txt}{role_txt}")
        lines.append("")
        lines.append("```")
        lines.append(prompt)
        lines.append("```")
        lines.append("")
    return "\n".join(lines)


def select_heroes(clusters):
    """CR >= HERO_CR_FLOOR OR role == 'leader', across all clusters. Ordered by CR
    descending (name tiebreak) — the biggest names first."""
    heroes = []
    for items in clusters.values():
        for c in items:
            if (c.get("cr") or 0) >= HERO_CR_FLOOR or c.get("role") == "leader":
                heroes.append(c)
    heroes.sort(key=lambda c: (-(c.get("cr") or 0), c["name"]))
    return heroes


def main():
    os.makedirs(OUT_DIR, exist_ok=True)
    bestiary = load_bestiary()
    clusters = cluster_creatures(bestiary)
    sheets = pack_sheets(clusters)

    manifest = {
        "_generated_by": "build/gen-sprite-manifests.py",
        "_source": "data/bestiary.js (BESTIARY)",
        "_note": "GENERATED — do not hand-edit; re-run the generator.",
        "gridSize": GRID,
        "cellsPerSheet": CELLS_PER_SHEET,
        "sheetCount": len(sheets),
        "totalCreatures": sum(len(s) for s in sheets),
        "sheets": {},
    }

    digits = max(2, len(str(len(sheets))))
    for idx, creatures in enumerate(sheets, start=1):
        sheet_id = f"sheet-{idx:0{digits}d}"
        md_path = os.path.join(OUT_DIR, f"{sheet_id}.md")
        with open(md_path, "w") as f:
            f.write(format_sheet_md(idx, creatures))
        manifest["sheets"][sheet_id] = {
            "count": len(creatures),
            "clusterTypes": sorted(set(c["type"] for c in creatures)),
            "slugs": [c["id"] for c in creatures],
        }

    with open(os.path.join(OUT_DIR, "MASTER-SPEC.md"), "w") as f:
        f.write(format_master_spec_md())

    heroes = select_heroes(clusters)
    with open(os.path.join(OUT_DIR, "heroes.md"), "w") as f:
        f.write(format_heroes_md(heroes))
    manifest["heroes"] = [h["id"] for h in heroes]

    manifest_path = os.path.join(OUT_DIR, "manifest.json")
    with open(manifest_path, "w") as f:
        json.dump(manifest, f, indent=2)
        f.write("\n")

    print(f"Wrote {len(sheets)} sheet prompts + MASTER-SPEC.md + heroes.md + manifest.json to {OUT_DIR}")
    print(f"Total creatures: {manifest['totalCreatures']} (bestiary had {len(bestiary)}, "
          f"{len(bestiary) - manifest['totalCreatures']} dropped as non-creature rows)")
    print(f"Heroes (CR >= {HERO_CR_FLOOR} or role: leader): {len(heroes)}")
    for idx, creatures in enumerate(sheets, start=1):
        sheet_id = f"sheet-{idx:0{digits}d}"
        types = manifest["sheets"][sheet_id]["clusterTypes"]
        print(f"  {sheet_id}: {len(creatures)} creatures, types={types}")


if __name__ == "__main__":
    main()
