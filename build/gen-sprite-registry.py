def load_json(path, default=None):
    if not os.path.exists(path):
        if default is not None:
            return default
        raise SystemExit(f"missing required file: {path}")
    with open(path, "r", encoding="utf-8") as f:
        return json.load(f)


def norm(s):
    """case/punctuation-insensitive fallback key for the name join."""
    return re.sub(r"[^a-z0-9]+", "", s.lower())


def load_bestiary_by_realm():
    draft = load_json(BESTIARY_DRAFT)
    by_realm = {}
    for entry in draft:
        if "realm" not in entry or "creatures" not in entry:
            continue  # skip the leading _review sidecar block
        realm = entry["realm"]
        exact = {}
        loose = {}
        for c in entry["creatures"]:
            exact[c["name"]] = c
            loose.setdefault(norm(c["name"]), c)
        by_realm[realm] = {"exact": exact, "loose": loose}
    # The "fantasy" sheet realm is the base game's own 510-entry bestiary (data/bestiary.js),
    # not a realm block in the draft JSON — join it against BESTIARY directly (integration fix
    # 2026-07-09; without this every fantasy monster cell reads as unjoined and coverage lies).
    bjs = open(os.path.join(ROOT, "data", "bestiary.js"), encoding="utf-8").read()
    exact, loose = {}, {}
    for m in re.finditer(r'"([a-z0-9-]+)":\s*\{[^{}]*?"name":\s*"((?:[^"\\]|\\.)*)"', bjs):
        key, name = m.group(1), json.loads('"' + m.group(2) + '"')
        c = {"name": name, "frame": key, "role": None, "cr": None, "type": None, "size": None}
        for fld in ("cr", "role", "type", "size"):
            fm = re.search(r'"%s":\s*("(?:[^"\\]|\\.)*"|[0-9.]+)' % fld, bjs[m.start():m.start() + 600])
            if fm:
                try:
                    c[fld] = json.loads(fm.group(1))
                except ValueError:
                    pass
        exact.setdefault(name, c)
        loose.setdefault(norm(name), c)
    by_realm["fantasy"] = {"exact": exact, "loose": loose}
    return by_realm


def load_sizing_sources():
    """Returns (corpus_sizing_by_slug, v3_by_sheet_cell). corpus_sizing_by_slug keys are
    registry slugs directly. v3_by_sheet_cell keys are (sheetStem, cellNumber) reconstructed
    from each v3-sizing.json entry's `replaces` field, values are {feet, scaleVsHuman}."""
    corpus = load_json(CORPUS_SIZING, default={})
    v3 = load_json(V3_SIZING, default={})
    v3_by_sheet_cell = {}
    for _key, e in v3.items():
        m = V3_REPLACES_RE.match(e.get("replaces") or "")
        if not m:
            continue
        sheet_stem, row, col = m.group(1), int(m.group(2)), int(m.group(3))
        n = (row - 1) * V3_GRID_COLS + col
        if isinstance(e.get("feet"), (int, float)):
            v3_by_sheet_cell[(sheet_stem, n)] = {"feet": e["feet"], "scaleVsHuman": e.get("scaleVsHuman")}
    return corpus, v3_by_sheet_cell


def sizing_for(slug, sheet, cell, corpus_sizing, v3_by_sheet_cell):
    """Feet/scaleTrue for a cut slug, per BEAUTY-WAVE.md VP1's fold priority: corpus-sizing.json
    (direct slug join) first, then the v3-sizing.json replaces-join, else None (skip)."""
    hit = corpus_sizing.get(slug)
    if hit and isinstance(hit.get("feet"), (int, float)):
        return hit["feet"]
    hit = v3_by_sheet_cell.get((sheet, cell))
    if hit:
        return hit["feet"]
    return None


def title_from_slug(slug, prefix):
    """VQ2-RESPEC.md S4 Part B — kebab -> Title Case for an orphan fold-in slug, e.g.
    'spr-fantasy-adult-gold-dragon' with prefix 'spr-fantasy-' -> 'Adult Gold Dragon'. Purely
    mechanical (no dictionary lookups) — a lossy kebab artifact (an embedded possessive's stray
    "-s-", a multi-identity slug concatenating two creature names) produces an ugly-but-honest
    title rather than an invented one; those either miss the bestiary join below (nulls, loud in
    the inventory report) or over-match harmlessly."""
    body = slug[len(prefix):] if slug.startswith(prefix) else slug
    return " ".join(w.capitalize() for w in body.split("-") if w)


def load_faceted_cut_report():
    """dev/model-qa/faceted-cut-report.json's slugs{} (S2's cut sidecar) — per-slug
    contentBounds [x0,y0,x1,y1] (normalized alpha bbox) + footContact (normalized x-center of
    the lowest opaque row, i.e. an already-normalized footX). Missing file -> {} (no candidates
    yet; every entry falls through to the legacy/default foot-contact branch below)."""
    report = load_json(FACETED_CUT_REPORT, default={})
    return report.get("slugs", {}) if isinstance(report, dict) else {}


def standee_contract_for(overlay_entry, cut_record):
    """B1 contract fields: footX, footY, contentBounds, alphaCutoff, shadowProfile.

    Priority (VQ2-RESPEC.md S3 / PHASE-3-WAVE-2-SPECS.md B1):
      1. faceted cut-report record (S2) -> contentBounds direct, footX = footContact (already
         x-normalized), footY = contentBounds[3] (the alpha bbox's bottom edge, same row the
         cut report's foot_contact_x measured — normalized top-down, 0=top/1=bottom).
      2. legacy overlay `floor` (ground-contact fraction UP FROM THE BOTTOM edge) -> footY =
         1 - floor (converted to the same top-down convention), footX defaults to bbox center
         (floor carries no x measurement). contentBounds stays null (not measured for legacy-only
         art).
      3. neither -> bbox bottom-center default (footX 0.5, footY 1.0), contentBounds null.
    """
    content_bounds = None
    foot_x = foot_y = None

    if cut_record and isinstance(cut_record.get("contentBounds"), list) and len(cut_record["contentBounds"]) == 4:
        content_bounds = [round(float(v), 6) for v in cut_record["contentBounds"]]
        if isinstance(cut_record.get("footContact"), (int, float)):
            foot_x = round(float(cut_record["footContact"]), 6)
        foot_y = content_bounds[3]

    if foot_x is None or foot_y is None:
        floor = overlay_entry.get("floor")
        if isinstance(floor, (int, float)) and 0 < floor <= 0.9:
            foot_x = 0.5
            foot_y = round(1.0 - float(floor), 4)
        else:
            foot_x = 0.5
            foot_y = 1.0

    return {
        "footX": foot_x,
        "footY": foot_y,
        "contentBounds": content_bounds,
        "alphaCutoff": ALPHA_CUTOFF_DEFAULT,
        "shadowProfile": SHADOW_PROFILE_DEFAULT,
    }


def world_height_for(feet, size):
    """worldHeight + heightSource, in source-priority order: (1) measured — an existing `feet`
    value (corpus-sizing/v3-sizing joins, folded above for cut entries); (2) band-default — the
    SRD size-band midpoint ladder, keyed off the bestiary-joined `size`; (3) missing — neither
    resolves, so worldHeight stays null rather than a silent guess."""
    if isinstance(feet, (int, float)):
        return feet, "measured"
    band = SIZE_BAND_DEFAULT_FEET.get((size or "").strip().lower())
    if band is not None:
        return band, "band-default"
    return None, "missing"


def join_creature(realm, name, bestiary_by_realm):
    realm_idx = bestiary_by_realm.get(realm)
    if not realm_idx:
        return None
    if name in realm_idx["exact"]:
        return realm_idx["exact"][name]
    return realm_idx["loose"].get(norm(name))


def auto_tags(realm, kind, role, ctype, size):
    tags = []
    for v in (realm, kind, role, (ctype or "").lower() or None, (size or "").lower() or None):
        if v:
            tags.append(v)
    return tags


def fold_in_orphans(entries, faceted_cut_slugs, bestiary_by_realm, corpus_sizing, v3_by_sheet_cell,
                     admit_faceted=False):
    """VQ2-RESPEC.md S4 Part B — the 60 orphan fold-ins (S3's honest documented deviation:
    write_inventory_report's own docstring called this "NOT invented as new SPRITE_REGISTRY
    entries; that would grow the registry beyond its join source, out of scope for THAT unit").
    This unit extends the generator with a direct entry source: every faceted-cut-report slug
    (`dev/model-qa/faceted-cut-report.json`) that has NO real v2-manifest-cell join AND has an
    actual cut file on disk gets a new registry row here.

    Per slug: name is derived mechanically from the slug (kebab -> Title Case, title_from_slug);
    non-pc (`spr-fantasy-*`) slugs are bestiary-joined by that name within realm=fantasy for
    role/cr/type/size/frame (the SAME join_creature exact-then-loose join every manifest cell
    uses above) — a miss leaves those fields null, never invented. `spr-pc-*` slugs skip the
    bestiary join entirely (realm="pc", kind="pc", matching the existing PC-entry convention:
    PCs were never bestiary creatures). sheet:"faceted-direct"/cell:null mark "no manifest cell
    ever existed for this slug"; status:"cut" because the art is real; legacyAsset:null because
    no v3 wave ever cut this identity; candidateAsset points at the real faceted file.
    worldHeight/heightSource use the SAME measured -> band-default -> missing ladder as every
    other entry (sizing_for/world_height_for, unmodified) — corpus-sizing.json carries no keys
    for these slugs at time of writing (they never existed as a cut slug before), so every one
    of these rows resolves to band-default (bestiary join succeeded, size known) or missing
    (join failed) unless a future corpus-sizing pass adds a measured value.

    Returns the list of (slug, entry) pairs added, in sorted-slug order (deterministic across
    regens) — entries[] is mutated in place, appended so pre-existing entries keep their exact
    prior emit order/bytes (the S4 byte-stability gate)."""
    added = []
    for slug in sorted(faceted_cut_slugs.keys()):
        existing = entries.get(slug)
        if existing is not None and existing.get("candidateAsset") is not None:
            continue  # already a real v2-manifest-cell join (S3 territory) — not an orphan
        if not os.path.exists(os.path.join(SPRITES_FACETED_DIR, f"{slug}.png")):
            continue  # cut-report lists it but the file is missing/quarantined — not this unit's job

        is_pc = slug.startswith("spr-pc-")
        realm = "pc" if is_pc else "fantasy"
        kind = "pc" if is_pc else "monster"
        prefix = "spr-pc-" if is_pc else "spr-fantasy-"
        name = title_from_slug(slug, prefix)

        role = cr = ctype = size = frame = None
        if not is_pc:
            match = join_creature(realm, name, bestiary_by_realm)
            if match:
                role = match.get("role")
                cr = match.get("cr")
                ctype = match.get("type")
                size = match.get("size")
                frame = match.get("frame")

        tags = auto_tags(realm, kind, role, ctype, size)

        entry = {
            "realm": realm, "kind": kind, "name": name, "role": role, "cr": cr,
            "type": ctype, "size": size, "frame": frame, "tags": tags,
            "sheet": "faceted-direct", "cell": None, "status": "cut",
        }

        feet = sizing_for(slug, "faceted-direct", None, corpus_sizing, v3_by_sheet_cell)
        if isinstance(feet, (int, float)):
            entry["feet"] = feet
            entry["scaleTrue"] = round(float(feet) / 5.5, 2)

        entry["legacyAsset"] = None
        entry["candidateAsset"] = f"assets/sprites-faceted/{slug}.png"
        entry["artStyleVersion"] = "faceted-v1"
        entry["qaStatus"] = QA_STATUS_CANDIDATE
        # S5 — THE FLIP. --admit-faceted admits every slug with a real cut file (these orphan
        # rows only ever exist because one does, per the guard above); omit the flag and every
        # entry stays "legacy" (RUNTIME_ADMITTED_DEFAULT) — the re-derivable retreat.
        entry["runtimeAdmitted"] = "candidate" if admit_faceted else RUNTIME_ADMITTED_DEFAULT

        cut_record = faceted_cut_slugs.get(slug)
        contract = standee_contract_for({}, cut_record)
        entry.update(contract)

        world_height, height_source = world_height_for(entry.get("feet"), size)
        entry["worldHeight"] = world_height
        entry["heightSource"] = height_source

        entries[slug] = entry
        added.append((slug, entry))
    return added


def build_bestiary_id_map(entries):
    """VQ2-RESPEC.md S4 Part A (ledger P0 #1, "Giant Rat renders as a robed humanoid") —
    deterministic bestiary-id -> registry-slug index, built from the SAME realm-bestiary join
    this generator already performs above: entry["frame"] IS the joined bestiary id (the fantasy
    branch of load_bestiary_by_realm sets it to the data/bestiary.js dict key, e.g. "giant-rat";
    the realm-draft branch sets it to REALM_BESTIARY's own "frame"/"model" field) — the SAME
    field src/engine/theater-data.js's theaterUnitsFrom stamps onto a combat unit as
    `f.modelKey || f.statId` (recipeSlug). src/ui/theater-boot.js's spriteEntryFor consults this
    map by EXACT recipeSlug match first, before falling back to its existing normalized-name
    linear scan — an id never carries the "Giant Rat" vs "giant-rat" spacing/case ambiguity a
    display name does, so no collision class exists at this join tier.

    Only `status:"cut"` entries are eligible (spriteEntryFor never resolves a pending entry) and
    a `verdict:"fail"` entry is excluded (review-failed art must still fall through to the 3D
    chain). On a genuine collision — two different cut entries joined to the SAME bestiary id, a
    real duplicate-art situation, not a normalization artifact — the first in slug-sorted order
    wins (deterministic across regens) and every collision is returned so it stays visible
    (printed by the caller), never silently dropped."""
    by_id = {}
    collisions = []
    for slug in sorted(entries.keys()):
        e = entries[slug]
        frame = e.get("frame")
        if not frame or e.get("status") != "cut" or e.get("verdict") == "fail":
            continue
        if frame in by_id:
            collisions.append((frame, by_id[frame], slug))
            continue
        by_id[frame] = slug
    return by_id, collisions


def emit_bestiary_id_map(by_id):
    lines = ["const SPRITE_BY_BESTIARY_ID={\n"]
    for bid in sorted(by_id.keys()):
        lines.append(f"  {js_str(bid)}: {js_str(by_id[bid])},\n")
    lines.append("};\n")
    return "".join(lines)


def js_str(v):
    return json.dumps(v)


def emit_entry(slug, e):
    fields = []
    fields.append(f'realm:{js_str(e["realm"])}')
    fields.append(f'kind:{js_str(e["kind"])}')
    fields.append(f'name:{js_str(e["name"])}')
    fields.append(f'role:{js_str(e["role"]) if e["role"] is not None else "null"}')
    fields.append(f'cr:{json.dumps(e["cr"]) if e["cr"] is not None else "null"}')
    fields.append(f'type:{js_str(e["type"]) if e["type"] is not None else "null"}')
    fields.append(f'size:{js_str(e["size"]) if e["size"] is not None else "null"}')
    fields.append(f'frame:{js_str(e["frame"]) if e["frame"] is not None else "null"}')
    fields.append("tags:" + json.dumps(e["tags"]))
    fields.append(f'sheet:{js_str(e["sheet"])}')
    fields.append(f'cell:{json.dumps(e["cell"])}')
    fields.append(f'status:{js_str(e["status"])}')
    if e.get("reusable") is not None:
        fields.append(f'reusable:{js_str(e["reusable"])}')
    if e.get("redlined") is not None:
        fields.append("redlined:" + json.dumps(bool(e["redlined"])))
    if e.get("scale") is not None:
        fields.append(f'scale:{json.dumps(e["scale"])}')
    if e.get("feet") is not None:
        fields.append(f'feet:{json.dumps(e["feet"])}')
    if e.get("scaleTrue") is not None:
        fields.append(f'scaleTrue:{json.dumps(e["scaleTrue"])}')
    if e.get("floor") is not None:
        fields.append(f'floor:{json.dumps(e["floor"])}')
    if e.get("verdict") is not None:
        fields.append(f'verdict:{js_str(e["verdict"])}')
    if e.get("note") is not None:
        fields.append(f'note:{js_str(e["note"])}')
    # S3 / B1 — standee contract (always present).
    fields.append(f'footX:{json.dumps(e["footX"])}')
    fields.append(f'footY:{json.dumps(e["footY"])}')
    fields.append('contentBounds:' + (json.dumps(e["contentBounds"]) if e["contentBounds"] is not None else "null"))
    fields.append(f'alphaCutoff:{json.dumps(e["alphaCutoff"])}')
    fields.append(f'shadowProfile:{js_str(e["shadowProfile"])}')
    fields.append('worldHeight:' + (json.dumps(e["worldHeight"]) if e["worldHeight"] is not None else "null"))
    fields.append(f'heightSource:{js_str(e["heightSource"])}')
    # S3 / B1 — faceted-migration art admission (always present).
    fields.append('legacyAsset:' + (js_str(e["legacyAsset"]) if e["legacyAsset"] is not None else "null"))
    fields.append('candidateAsset:' + (js_str(e["candidateAsset"]) if e["candidateAsset"] is not None else "null"))
    fields.append(f'artStyleVersion:{js_str(e["artStyleVersion"])}')
    fields.append('qaStatus:' + (js_str(e["qaStatus"]) if e["qaStatus"] is not None else "null"))
    fields.append(f'runtimeAdmitted:{js_str(e["runtimeAdmitted"])}')
    return " \"" + slug + "\": {" + ", ".join(fields) + "},\n"


