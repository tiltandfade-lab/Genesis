#!/usr/bin/env python3
"""Genesis build — generate data/monster-flavor.js from dev/model-qa/monster-flavor.json.

docs/MONSTER-FLAVOR-TABLES.md §3 (Unit F1). The regular 510-entry bestiary corpus has no
per-creature narrative desc and no d8 flavor table — this is the generated sidecar that adds
both without ever touching Adam's Asset Library monster source files or data/bestiary.js.

Source of truth: dev/model-qa/monster-flavor.json — a flat object keyed by bestiary id:
  { "<bestiary-id>": { "desc": "...", "flavorTable": {"die":"d8","mode":"variant"|"hook",
                                                        "rows":[{n,band,text}, ...] } }, ... }
Edit that file, then re-run this. NEVER hand-edit data/monster-flavor.js.

--check validates without writing (§1 authoring contract + §3 coverage):
  - every key is a real data/bestiary.js BESTIARY id
  - flavorTable.die == "d8", rows has exactly 8 entries, n runs 1..8
  - band mapping: rows 1-5 == Grounded, row 6 == Textured, row 7 == Strange,
    row 8 == Volatile (or Mythic — apex/high-role creatures may earn Mythic at r8)
  - mode is present and is one of variant|hook
  - full run (no --allow-partial): every one of the 510 BESTIARY ids must have an entry
  --allow-partial: skip the 510/510 coverage requirement (authoring is in flight); still
    validates the shape of whatever rows exist so far.

Run: python3 build/gen-monster-flavor.py                        (writes data/monster-flavor.js)
     python3 build/gen-monster-flavor.py --check                 (validates only, no write)
     python3 build/gen-monster-flavor.py --check --allow-partial (validates partial corpus)

After regenerating: python3 build/check-manifest.py
"""
import json, os, re, subprocess, sys, tempfile
from collections import OrderedDict

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SOURCE = os.path.join(ROOT, "dev", "model-qa", "monster-flavor.json")
BESTIARY_JS = os.path.join(ROOT, "data", "bestiary.js")
OUT = os.path.join(ROOT, "data", "monster-flavor.js")

VALID_MODES = ("variant", "hook")
LOW_BANDS = {1: "Grounded", 2: "Grounded", 3: "Grounded", 4: "Grounded", 5: "Grounded",
             6: "Textured", 7: "Strange"}
ROW8_BANDS = ("Volatile", "Mythic")

HEADER = (
    "/* GENERATED by build/gen-monster-flavor.py from dev/model-qa/monster-flavor.json "
    "— never hand-edit. Regular-bestiary flavor sidecar (docs/MONSTER-FLAVOR-TABLES.md "
    "§3): per-creature desc + a spice-graded d8 flavor table (variant|hook). Adam's "
    "Asset Library monster files and data/bestiary.js are untouched by this layer; the 104 "
    "hand-authored custom d10 tables (his) coexist, never replaced. */\n"
)


def load_bestiary_ids():
    """Extract BESTIARY's keys via node (mirrors gen-realm-bestiary.py's approach — the file
    is multi-MB, too big for a regex-free hand parse to be worth trusting)."""
    src = open(BESTIARY_JS, encoding="utf-8").read()
    with tempfile.NamedTemporaryFile("w", suffix=".js", delete=False, dir=ROOT) as tf:
        tf.write(src)
        tf.write("\nrequire('fs').writeFileSync(process.argv[2], JSON.stringify(Object.keys(BESTIARY)));\n")
        script_path = tf.name
    out_path = os.path.join(ROOT, "._bestiary_ids_tmp.json")
    try:
        result = subprocess.run(["node", script_path, out_path], capture_output=True, text=True, cwd=ROOT)
        if result.returncode != 0:
            sys.stderr.write("gen-monster-flavor: failed to extract BESTIARY ids via node\n")
            sys.stderr.write(result.stderr)
            sys.exit(1)
        with open(out_path, encoding="utf-8") as f:
            return set(json.load(f))
    finally:
        if os.path.exists(script_path):
            os.remove(script_path)
        if os.path.exists(out_path):
            os.remove(out_path)


def load_source():
    with open(SOURCE, encoding="utf-8") as f:
        return json.load(f, object_pairs_hook=OrderedDict)


def validate(data, bestiary_ids, allow_partial):
    problems = []

    for mid, entry in data.items():
        if mid not in bestiary_ids:
            problems.append(f"{mid}: not a data/bestiary.js BESTIARY id")
            continue

        if not isinstance(entry, dict):
            problems.append(f"{mid}: entry must be an object")
            continue

        desc = entry.get("desc")
        if not desc or not isinstance(desc, str) or not desc.strip():
            problems.append(f"{mid}: missing/empty desc")

        ft = entry.get("flavorTable")
        if not isinstance(ft, dict):
            problems.append(f"{mid}: missing flavorTable")
            continue

        if ft.get("die") != "d8":
            problems.append(f"{mid}: flavorTable.die must be \"d8\" (got {ft.get('die')!r})")

        mode = ft.get("mode")
        if mode not in VALID_MODES:
            problems.append(f"{mid}: flavorTable.mode must be one of {VALID_MODES} (got {mode!r})")

        rows = ft.get("rows")
        if not isinstance(rows, list) or len(rows) != 8:
            problems.append(f"{mid}: flavorTable.rows must have exactly 8 rows (got {len(rows) if isinstance(rows, list) else type(rows)})")
            continue

        seen_n = set()
        apex_role = str(entry.get("role") or "").lower() in ("apex",)
        for row in rows:
            if not isinstance(row, dict):
                problems.append(f"{mid}: row {row!r} must be an object")
                continue
            n = row.get("n")
            band = row.get("band")
            text = row.get("text")
            if n not in range(1, 9):
                problems.append(f"{mid}: row n must be 1..8 (got {n!r})")
                continue
            seen_n.add(n)
            if not text or not isinstance(text, str) or not text.strip():
                problems.append(f"{mid}: row {n} missing text")
            if n <= 7:
                expect = LOW_BANDS[n]
                if band != expect:
                    problems.append(f"{mid}: row {n} band must be {expect!r} (got {band!r})")
            else:  # n == 8
                if band not in ROW8_BANDS:
                    problems.append(f"{mid}: row 8 band must be one of {ROW8_BANDS} (got {band!r})")
                if band == "Mythic" and not apex_role:
                    problems.append(f"{mid}: row 8 band is Mythic but creature role is not apex")

        if seen_n != set(range(1, 9)):
            problems.append(f"{mid}: rows must cover n=1..8 exactly once (got {sorted(seen_n)})")

    if not allow_partial:
        missing = bestiary_ids - set(data.keys())
        if missing:
            problems.append(f"coverage: {len(missing)}/510 BESTIARY ids missing from monster-flavor.json (--allow-partial to skip this check): {sorted(missing)[:10]}{'...' if len(missing) > 10 else ''}")

    return problems


def emit(data):
    lines = [HEADER, "const MONSTER_FLAVOR={\n"]
    for i, (mid, entry) in enumerate(data.items()):
        comma = "," if i < len(data) - 1 else ""
        lines.append(f" {json.dumps(mid)}: {json.dumps(entry, ensure_ascii=False)}{comma}\n")
    lines.append("};\n")
    with open(OUT, "w", encoding="utf-8") as f:
        f.writelines(lines)


def main():
    check_only = "--check" in sys.argv
    allow_partial = "--allow-partial" in sys.argv

    if not os.path.exists(SOURCE):
        sys.stderr.write(f"gen-monster-flavor: source not found: {SOURCE}\n")
        sys.exit(1)

    data = load_source()
    bestiary_ids = load_bestiary_ids()
    problems = validate(data, bestiary_ids, allow_partial)

    if problems:
        sys.stderr.write(f"gen-monster-flavor: {len(problems)} problem(s):\n")
        for p in problems:
            sys.stderr.write(f"  - {p}\n")
        sys.exit(1)

    if check_only:
        print(f"gen-monster-flavor --check: OK ({len(data)} entries, allow_partial={allow_partial})")
        return

    emit(data)
    print(f"gen-monster-flavor: wrote {OUT} ({len(data)} entries)")


if __name__ == "__main__":
    main()
